/**
 * Creates drop-in folders for every registered skill (55) and unique normal (11×8).
 *
 *   node scripts/prepare-skill-slots.mjs
 *
 * Does not generate PNG. Status stays READY FOR ART until real frames are dropped.
 */
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve('public/sprites')
const registryFile = path.resolve('src/combat/anim/registry.ts')
const outIndex = path.resolve('src/combat/anim/skillSlotIndex.ts')

const FIGHTERS = [
  'rimuru', 'milim', 'diablo', 'benimaru', 'shion', 'veldora',
  'hinata', 'guy', 'shuna', 'souei', 'hakurou',
]

const NORMAL_SUFFIXES = [
  'light_1', 'light_2', 'light_3', 'medium', 'heavy', 'air_light', 'air_heavy', 'down_light',
]

function parseSkillDefs(source) {
  const defs = []
  const re = /def\('(\w+)', '([^']+)', '([^']+)', '([^']+)', (\d)\)/g
  for (const match of source.matchAll(re)) {
    defs.push({
      fighterId: match[1],
      attackId: match[2],
      animId: match[3],
      skillName: match[4],
      slot: Number(match[5]),
    })
  }
  return defs
}

function writeSlot(dir, payload) {
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, '.gitkeep'), '')
  fs.writeFileSync(path.join(dir, 'anim.json'), `${JSON.stringify(payload, null, 2)}\n`)
}

function skillPayload(def) {
  return {
    fighterId: def.fighterId,
    attackId: def.attackId,
    animId: def.animId,
    skillName: def.skillName,
    slot: def.slot,
    type: 'sequence',
    status: 'READY FOR ART',
    fps: 60,
    loop: false,
    projectileInSprite: false,
    timing: {
      source: 'AttackData is the source of truth',
      releaseFrame: 'attack.startup',
      startupStart: '0',
      startupEnd: 'releaseFrame - 1',
      activeStart: 'releaseFrame',
      recoveryStart: 'activeEnd + 1',
    },
    vfx: {
      cast: 'energy_charge when startup >= 8',
      release: 'AttackData.vfx',
      travel: 'rangedShape for projectile/beam',
      impact: 'impact_ultimate on slot 4',
    },
    dropIn: '001.png then npm run index-sprites',
  }
}

function normalPayload(fighterId, animId) {
  return {
    fighterId,
    animId,
    kind: 'normal',
    status: 'READY FOR ART',
    note: 'Unique normals. Runtime may still fallback to rimuru/milim until these PNGs exist.',
    dropIn: '001.png then npm run index-sprites',
  }
}

const registry = fs.readFileSync(registryFile, 'utf8')
const skills = parseSkillDefs(registry)
if (skills.length !== 55) {
  throw new Error(`[prepare-skill-slots] expected 55 skill defs, parsed ${skills.length}`)
}

const skillRecords = []
for (const def of skills) {
  const folder = path.join(root, def.fighterId, def.animId)
  writeSlot(folder, skillPayload(def))
  skillRecords.push({
    fighterId: def.fighterId,
    attackId: def.attackId,
    animId: def.animId,
    skillName: def.skillName,
    slot: def.slot,
    folder: `public/sprites/${def.fighterId}/${def.animId}`,
    hasAnimJson: true,
    kind: 'skill',
  })
}

const formBlade = path.join(root, 'rimuru', 'rimuru-slime', 'rimuru_water_blade')
if (fs.existsSync(formBlade)) {
  writeSlot(formBlade, {
    ...skillPayload(skills.find((item) => item.animId === 'rimuru_water_blade')),
    form: 'rimuru-slime',
    note: 'Form-specific drop-in. Optional; base folder is public/sprites/rimuru/rimuru_water_blade/',
  })
}

const normalRecords = []
for (const fighterId of FIGHTERS) {
  for (const suffix of NORMAL_SUFFIXES) {
    const animId = `${fighterId}_${suffix}`
    const folder = path.join(root, fighterId, animId)
    const alt = path.join(root, fighterId, 'normals', animId)
    writeSlot(folder, normalPayload(fighterId, animId))
    writeSlot(alt, { ...normalPayload(fighterId, animId), dropIn: 'alternate path; clip id stays ' + animId })
    normalRecords.push({
      fighterId,
      animId,
      folder: `public/sprites/${fighterId}/${animId}`,
      hasAnimJson: true,
      kind: 'normal',
    })
  }
}

const body = `/** Generated by scripts/prepare-skill-slots.mjs. Do not edit by hand. */
export interface SkillSlotRecord {
  fighterId: string
  attackId?: string
  animId: string
  skillName?: string
  slot?: number
  folder: string
  hasAnimJson: boolean
  kind: 'skill' | 'normal'
}

export const SKILL_SLOT_FOLDERS: SkillSlotRecord[] = ${JSON.stringify(skillRecords, null, 2)}

export const NORMAL_SLOT_FOLDERS: SkillSlotRecord[] = ${JSON.stringify(normalRecords, null, 2)}
`

fs.writeFileSync(outIndex, body)
console.info(`[prepare-skill-slots] ${skillRecords.length} skills, ${normalRecords.length} normals -> ${path.relative(process.cwd(), outIndex)}`)
